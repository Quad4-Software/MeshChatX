// Generates js/generated/mdiIconData.ts: the full valid icon-name list plus
// path data for icons referenced by source literals or curated extras.
// Path data for the remaining ~7000 icons stays in the lazily imported
// @mdi/js chunk so it never lands on the initial-load critical path.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import {
    collectLiteralIconNames,
    mdiKeyToListName,
    resolveMdiExportKey,
    CURATED_EXTRA_ICON_NAMES,
} from "./mdi-icon-scan.mjs";

const require = createRequire(import.meta.url);
const mdi = require("@mdi/js");

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const frontendRoot = path.join(repoRoot, "meshchatx", "src", "frontend");
const outDir = path.join(frontendRoot, "js", "generated");
const outFile = path.join(outDir, "mdiIconData.ts");

const names = Object.keys(mdi).map(mdiKeyToListName).sort();

const literals = collectLiteralIconNames(frontendRoot);
const used = new Map();
const unresolved = [];
for (const name of [...literals, ...CURATED_EXTRA_ICON_NAMES]) {
    const key = resolveMdiExportKey(name, mdi);
    if (key && mdi[key]) {
        used.set(key, mdi[key]);
    } else {
        unresolved.push(name);
    }
}
if (unresolved.length > 0) {
    console.warn(`generate-mdi-icons: unresolved literal icon names: ${unresolved.join(", ")}`);
}

const lines = [
    "// SPDX-License-Identifier: 0BSD",
    "//",
    "// Generated by scripts/build/generate-mdi-icons.mjs. Do not edit by hand.",
    "// Regenerate with: pnpm run generate:mdi-icons",
    "",
    `export const MDI_ICON_NAMES: readonly string[] = ${JSON.stringify(names)};`,
    "",
    "export const MDI_NAME_SET: ReadonlySet<string> = new Set(MDI_ICON_NAMES);",
    "",
    "// Path data for icons referenced as literals in source, plus curated",
    "// dynamic defaults (backend-sent names, fallbacks).",
    `export const MDI_USED_PATHS: Readonly<Record<string, string>> = ${JSON.stringify(Object.fromEntries([...used].sort()))};`,
    "",
];

fs.mkdirSync(outDir, { recursive: true });
let source = lines.join("\n");
try {
    const prettier = await import("prettier");
    const config = (await prettier.resolveConfig(outFile)) ?? {};
    source = await prettier.format(source, { ...config, filepath: outFile });
} catch {
    // Prettier is a devDependency; emit unformatted output when unavailable.
}
fs.writeFileSync(outFile, source);
console.log(
    `generate-mdi-icons: ${names.length} names, ${used.size} used paths -> ${path.relative(repoRoot, outFile)}`
);
